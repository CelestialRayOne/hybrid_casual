// Difficulty calibration report. Skipped by default (a few minutes); run with:
//   TUNING=1 npx vitest run src/core/tuning.test.ts --silent=false
// It recomputes every level's move budget with the casual player model over CALIBRATION_RUNS random attempts
// (calibrate.ts), prints the table and FAILS if the committed LEVEL_MOVES (levelTable.ts) is stale.
// To rewrite the table:
//   TUNING=1 TUNING_WRITE=1 npx vitest run src/core/tuning.test.ts --silent=false
import { describe, expect, it } from 'vitest';
import { CALIBRATION_RUNS, calibrateLevel, targetWinRate } from './calibrate';
import type { Calibration } from './calibrate';
import { LEVEL_COUNT, LEVEL_PARAMS, clearLevelCache, generateLevelReport, getLevel } from './generator';
import { LEVEL_MOVES } from './levelTable';

const env = (globalThis as { process?: { env?: Record<string, string | undefined> } }).process?.env ?? {};
const pct = (x: number) => `${Math.round(x * 100)}%`;
const f1 = (x: number) => x.toFixed(1);

function tableSource(moves: readonly (number | null)[]): string {
  return [
    '// GENERATED by `TUNING=1 TUNING_WRITE=1 npx vitest run src/core/tuning.test.ts` (calibrate.ts). Do not edit by hand:',
    '// change the levels or the casual model, then regenerate. The TUNING=1 report fails if this table is stale.',
    '//',
    '// Move budget per level (index = id - 1; null = unlimited).',
    'export const LEVEL_MOVES: readonly (number | null)[] = Object.freeze([',
    `  ${moves.map((m) => (m === null ? 'null' : String(m))).join(', ')},`,
    ']);',
    '',
  ].join('\n');
}

describe.skipIf(!env.TUNING)('difficulty calibration', () => {
  it('recomputes LEVEL_MOVES and prints the table', async () => {
    clearLevelCache();
    const rows: Calibration[] = [];
    const lines = [
      `Casual model: ${CALIBRATION_RUNS} random attempts per level (attempt seeds 1..${CALIBRATION_RUNS}).`,
      '| L | flags | moves | greedy | casual median | casual win | target | random win | goal | relics/attempt mean (min-max) | power uses/game mean (min-max) | bonus got | tries |',
      '|---|---|---|---|---|---|---|---|---|---|---|---|---|',
    ];
    for (let id = 1; id <= LEVEL_COUNT; id++) {
      const def = getLevel(id);
      const params = LEVEL_PARAMS[id - 1]!;
      const c = calibrateLevel(def);
      rows.push(c);
      const target = targetWinRate(id);
      const flags = [def.boss ? 'boss' : '', def.hard ? 'hard' : ''].filter(Boolean).join(' ') || '-';
      lines.push(
        `| ${id} | ${flags} | ${c.moves ?? 'inf'} | ${c.greedyMoves} | ${c.casualMedian} | ${pct(c.casualWinRate)} | ${target === null ? '-' : pct(target)} | ` +
          `${pct(c.randomWinRate)} | ${def.relics.length} | ${f1(c.relics.mean)} (${c.relics.min}-${c.relics.max}) | ` +
          `${f1(c.powerUses.mean)} (${c.powerUses.min}-${c.powerUses.max}) | ${f1(c.bonusCollected)} | ` +
          `${params.authored ? '-' : generateLevelReport(params).attempts} |`,
      );
    }
    console.log(lines.join('\n'));
    const fresh = rows.map((r) => r.moves);
    if (env.TUNING_WRITE) {
      const fs = (await import(/* @vite-ignore */ 'node:fs' as string)) as { writeFileSync(p: URL, d: string): void };
      fs.writeFileSync(new URL('./levelTable.ts', import.meta.url), tableSource(fresh));
      console.log('levelTable.ts rewritten');
    } else {
      expect(fresh).toEqual([...LEVEL_MOVES]);
    }
  }, 1_800_000);
});
